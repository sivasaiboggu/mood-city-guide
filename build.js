// Bundles the ESM sources into one classic script (bundle.js) so the app
// works from file://, where Chrome blocks ES-module imports (CORS).
// Run: node build.js   (also run automatically before screenshots)
const fs = require("fs");

function strip(src) {
  return src
    .replace(/^import .*$/gm, "")
    .replace(/^export const /gm, "const ")
    .replace(/^export function /gm, "function ")
    .replace(/^export /gm, "");
}

const data = strip(fs.readFileSync("data.js", "utf8"));
const engine = strip(fs.readFileSync("engine.mjs", "utf8"));
const app = strip(fs.readFileSync("app.js", "utf8"));

const out = `"use strict";\n// Generated by build.js — do not edit. Sources: data.js, engine.mjs, app.js\n${data}\n${engine}\n${app}\n`;
fs.writeFileSync("bundle.js", out);
console.log("wrote bundle.js", out.length, "bytes");
